def _fixture(name: str) -> str:
    return (FIXTURES / name).read_text(encoding="utf-8")


def _fingerprint(public_line: str) -> str:
    """`ssh-keygen -l` form, derived from a `.pub` line rather than from the verifier."""

    tokens = public_line.split()
    blob = base64.b64decode(tokens[tokens.index("ssh-ed25519") + 1])
    return "SHA256:" + base64.b64encode(hashlib.sha256(blob).digest()).decode().rstrip("=")


def _blob(armored: str) -> bytes:
    lines = [line for line in armored.splitlines() if line and not line.startswith("-----")]
    return base64.b64decode("".join(lines))


def _fields(blob: bytes) -> dict[str, tuple[int, int]]:
    """Byte span of each envelope field's VALUE inside the blob."""

    spans: dict[str, tuple[int, int]] = {}
    at = 10  # magic + version
    for name in ("key", "namespace", "reserved", "hash_algorithm", "signature"):
        size = int.from_bytes(blob[at : at + 4], "big")
        spans[name] = (at + 4, at + 4 + size)
        at += 4 + size
    return spans


def _flipped(data: bytes, index: int) -> bytes:
    return data[:index] + bytes([data[index] ^ 0x01]) + data[index + 1 :]


class Ed25519Tests(unittest.TestCase):
    def test_rfc8032_vectors_verify_and_one_flipped_bit_refuses(self) -> None:
        vectors = json.loads(_fixture("rfc8032.json"))["vectors"]
        self.assertEqual(
            [v["name"] for v in vectors],
            ["TEST 1", "TEST 2", "TEST 3", "TEST 1024", "TEST SHA(abc)"],
        )
        for vector in vectors:
            public = bytes.fromhex(vector["public_key"])
            message = bytes.fromhex(vector["message"])
            value = bytes.fromhex(vector["signature"])
            with self.subTest(vector=vector["name"]):
                self.assertTrue(_ed25519_verify(public, message, value))
                self.assertFalse(_ed25519_verify(public, message, _flipped(value, 0)))
                self.assertFalse(_ed25519_verify(public, message, _flipped(value, 32)))
                self.assertFalse(_ed25519_verify(_flipped(public, 0), message, value))
                changed = _flipped(message, len(message) - 1) if message else b"\x00"
                self.assertFalse(_ed25519_verify(public, changed, value))

    def test_the_test_signer_reproduces_every_rfc8032_signature(self) -> None:
        # Ed25519 signing is deterministic, so the G8 signer is pinned by the RFC itself.
        for vector in json.loads(_fixture("rfc8032.json"))["vectors"]:
            seed = bytes.fromhex(vector["seed"])
            with self.subTest(vector=vector["name"]):
                self.assertEqual(signer.public_key(seed).hex(), vector["public_key"])
                self.assertEqual(
                    signer.sign(seed, bytes.fromhex(vector["message"])).hex(), vector["signature"]
                )

    def test_wycheproof_under_the_strict_policy(self) -> None:
        raw = (FIXTURES / "wycheproof-ed25519.json").read_bytes()
        self.assertEqual(hashlib.sha256(raw).hexdigest(), WYCHEPROOF_SHA256)
        tally: Counter[tuple[str, bool]] = Counter()
        for group in json.loads(raw)["testGroups"]:
            public = bytes.fromhex(group["publicKey"]["pk"])
            for test in group["tests"]:
                verdict = _ed25519_verify(
                    public, bytes.fromhex(test["msg"]), bytes.fromhex(test["sig"])
                )
                tally[(test["result"], verdict)] += 1
        # `acceptable` = small- or mixed-order keys: the strict policy refuses all of them.
        self.assertEqual(
            dict(tally),
            {("valid", True): 117, ("invalid", False): 64, ("acceptable", False): 29},
        )

    def test_verify_is_total_and_refuses_non_canonical_encodings(self) -> None:
        vector = json.loads(_fixture("rfc8032.json"))["vectors"][0]
        public = bytes.fromhex(vector["public_key"])
        value = bytes.fromhex(vector["signature"])
        p = 2**255 - 19
        order = 2**252 + 27742317777372353535851937790883648493
        cases = {
            "short key": (public[:31], value),
            "long key": (public + b"\x00", value),
            "short signature": (public, value[:63]),
            "long signature": (public, value + b"\x00"),
            # y = p + 1 encodes the same point as y = 1 non-canonically.
            "y at or above p": ((p + 1).to_bytes(32, "little"), value),
            # y = 1 is the identity (x = 0); its sign bit set is a second, refused encoding.
            "x zero with the sign bit": ((1 | 1 << 255).to_bytes(32, "little"), value),
            "S equal to L": (public, value[:32] + order.to_bytes(32, "little")),
        }
        for name, (key, signature_bytes) in cases.items():
            with self.subTest(case=name):
                self.assertFalse(_ed25519_verify(key, b"", signature_bytes))
        for seed in range(200):
            noise = hashlib.sha512(seed.to_bytes(2, "big")).digest()
            with self.subTest(seed=seed):
                self.assertFalse(_ed25519_verify(noise[:32], b"m", noise))


class EnvelopeTests(unittest.TestCase):
    def setUp(self) -> None:
        self.message = (FIXTURES / "message").read_bytes()
        self.allowed = _fixture("allowed_signers")

    def verify(self, armored: str, **options: str) -> SignatureVerification:
        return verify_signature(
            self.message, armored, self.allowed, namespace=options.pop("namespace", FUNCTION_NAMESPACE), **options
        )

    def test_ssh_keygen_signatures_verify(self) -> None:
        alice = _fingerprint(_fixture("alice.pub"))
        for name, algorithm in (
            ("message.alice.sha512.sig", "sha512"),
            ("message.alice.sha256.sig", "sha256"),
        ):
            with self.subTest(fixture=name):
                checked = self.verify(_fixture(name))
                self.assertEqual(checked.principals, ("alice@example.test",))
                self.assertEqual(checked.fingerprint, alice)
                self.assertEqual(checked.hash_algorithm, algorithm)
        # Bob's line is a quoted principal list without a `namespaces` option.
        bob = self.verify(_fixture("message.bob.sig"), signer="builder@example.test")
        self.assertEqual(bob.principals, ("bob@example.test", "builder@example.test"))
        self.assertEqual(bob.fingerprint, _fingerprint(_fixture("bob.pub")))

    def test_other_namespaces_signers_and_key_types_refuse(self) -> None:
        with self.assertRaisesRegex(
            IntegrityError, "^signature namespace is file, expected cement-function-v3$"
        ):
            self.verify(_fixture("message.alice.file.sig"))
        with self.assertRaisesRegex(
            IntegrityError, "^the signing key is not allowed for that signer$"
        ):
            self.verify(_fixture("message.alice.sha512.sig"), signer="bob@example.test")
        with self.assertRaisesRegex(
            ValidationError, "^key type ecdsa-sha2-nistp256 is unsupported; use ssh-ed25519$"
        ):
            self.verify(_fixture("message.carol.sig"))

    def test_the_namespaces_option_limits_its_line(self) -> None:
        allowed = "\n".join(
            [
                signer.allowed_line("alice@x", ALICE, 'namespaces="cement-function-v3"'),
                signer.allowed_line("bob@x", BOB),
            ]
        )
        for seed, expected in ((ALICE, None), (BOB, ("bob@x",))):
            armored = signer.armor(signer.envelope(seed, b"data", namespace=b"other"))
            with self.subTest(expected=expected):
                if expected is None:
                    with self.assertRaisesRegex(
                        IntegrityError, "^the signing key is not an allowed signer for other$"
                    ):
                        verify_signature(b"data", armored, allowed, namespace="other")
                else:
                    checked = verify_signature(b"data", armored, allowed, namespace="other")
                    self.assertEqual(checked.principals, expected)

    def test_one_flipped_byte_in_any_field_or_the_data_refuses(self) -> None:
        allowed = signer.allowed_line("alice@x", ALICE)
        blob = signer.envelope(ALICE, b"bundle bytes", reserved=b"tag")
        spans = _fields(blob)
        expectations = {
            "key": (IntegrityError, "^the signing key is not an allowed signer for "),
            "namespace": (IntegrityError, "^signature namespace is "),
            "reserved": (IntegrityError, "^signature does not verify$"),
            "hash_algorithm": (ValidationError, "^signature hash algorithm .* is unsupported$"),
            "signature": (IntegrityError, "^signature does not verify$"),
        }
        self.assertEqual(
            verify_signature(
                b"bundle bytes", signer.armor(blob), allowed, namespace=FUNCTION_NAMESPACE
            ).principals,
            ("alice@x",),
        )
        for field, (error, pattern) in expectations.items():
            start, end = spans[field]
            # The last byte of the field: for the signature it lands in S, not in the type name.
            with self.subTest(field=field), self.assertRaisesRegex(error, pattern):
                verify_signature(
                    b"bundle bytes",
                    signer.armor(_flipped(blob, end - 1)),
                    allowed,
                    namespace=FUNCTION_NAMESPACE,
                )
            self.assertLess(start, end)
        with self.assertRaisesRegex(IntegrityError, "^signature does not verify$"):
            verify_signature(
                b"bundle bytez", signer.armor(blob), allowed, namespace=FUNCTION_NAMESPACE
            )

    def test_the_armor_and_blob_are_read_strictly(self) -> None:
        allowed = signer.allowed_line("alice@x", ALICE)
        good = signer.envelope(ALICE, b"d")
        armored = signer.armor(good)
        lines = armored.splitlines()
        rsa_value = signer.string(b"ssh-rsa") + signer.string(bytes(64))
        short_value = signer.string(b"ssh-ed25519") + signer.string(bytes(63))
        head = b"SSHSIG" + (1).to_bytes(4, "big") + signer.string(signer.key_blob(ALICE))
        tail = signer.string(b"") + signer.string(b"sha512")
        cases = {
            "no header": ("\n".join(lines[1:]), "^signature is not an armored SSH signature$"),
            "no footer": ("\n".join(lines[:-1]), "^signature is not an armored SSH signature$"),
            "text after the footer": (
                armored + "trailing\n",
                "^signature is not an armored SSH signature$",
            ),
            "a non-base64 character": (
                armored.replace(lines[1][:4], lines[1][:3] + "*", 1),
                "^signature armor is not valid base64$",
            ),
            # Lines split on `\n` alone: a form feed stays inside the base64 text.
            "a form feed inside a line": (
                armored.replace(lines[1], lines[1][:10] + "\f" + lines[1][10:], 1),
                "^signature armor is not valid base64$",
            ),
            "bad magic": (signer.armor(b"SSHSIH" + good[6:]), "^signature is not an SSHSIG envelope$"),
            "version 2": (
                signer.armor(good[:6] + (2).to_bytes(4, "big") + good[10:]),
                "^SSH signature version 2 is unsupported$",
            ),
            "trailing bytes": (signer.armor(good + b"\x00"), "^signature has trailing bytes$"),
            "truncated": (signer.armor(good[:-1]), "is truncated$"),
            "empty namespace": (
                signer.armor(head + signer.string(b"") + good[_fields(good)["reserved"][0] - 4 :]),
                "^signature namespace is empty$",
            ),
            "signature type differs": (
                signer.armor(head + signer.string(FUNCTION_NAMESPACE.encode()) + tail + signer.string(rsa_value)),
                "^signature key type differs from its public key$",
            ),
            "63-byte value": (
                signer.armor(head + signer.string(FUNCTION_NAMESPACE.encode()) + tail + signer.string(short_value)),
                "^signature value is not 64 bytes$",
            ),
        }
        for name, (text, pattern) in cases.items():
            with self.subTest(case=name), self.assertRaisesRegex(ValidationError, pattern):
                verify_signature(b"d", text, allowed, namespace=FUNCTION_NAMESPACE)
        for name, text in (
            ("trailing blank lines", armored + "\n\n\n"),
            ("CRLF line ends", armored.replace("\n", "\r\n")),
        ):
            with self.subTest(case=name):
                self.assertEqual(
                    verify_signature(b"d", text, allowed, namespace=FUNCTION_NAMESPACE).principals,
                    ("alice@x",),
                )

    def test_fido_and_other_key_types_are_refused_by_name(self) -> None:
        for key_type, pattern in (
            (
                b"sk-ssh-ed25519@openssh.com",
                "^sk-ssh-ed25519@openssh.com is a FIDO security key type; Cement verifies "
                "ssh-ed25519 keys only$",
            ),
            (
                b"sk-ecdsa-sha2-nistp256@openssh.com",
                "^sk-ecdsa-sha2-nistp256@openssh.com is a FIDO security key type",
            ),
            (b"ssh-rsa", "^key type ssh-rsa is unsupported; use ssh-ed25519$"),
        ):
            blob = (
                b"SSHSIG"
                + (1).to_bytes(4, "big")
                + signer.string(signer.key_blob(ALICE, key_type))
                + signer.string(FUNCTION_NAMESPACE.encode())
                + signer.string(b"")
                + signer.string(b"sha512")
                + signer.string(signer.string(key_type) + signer.string(bytes(64)))
            )
            with self.subTest(key_type=key_type), self.assertRaisesRegex(ValidationError, pattern):
                verify_signature(
                    b"d",
                    signer.armor(blob),
                    signer.allowed_line("alice@x", ALICE),
                    namespace=FUNCTION_NAMESPACE,
                )

    def test_arguments_are_type_checked_first(self) -> None:
        armored = signer.armor(signer.envelope(ALICE, b"d"))
        allowed = signer.allowed_line("alice@x", ALICE)
        for name, call, pattern in (
            ("text data", lambda: verify_signature("d", armored, allowed, namespace="n"), "^signed data must be bytes$"),  # type: ignore[arg-type]
            ("bytes signature", lambda: verify_signature(b"d", armored.encode(), allowed, namespace="n"), "^signature and allowed signers must be text$"),  # type: ignore[arg-type]
            ("empty namespace", lambda: verify_signature(b"d", armored, allowed, namespace=""), "^namespace must be non-empty text$"),
            ("empty signer", lambda: verify_signature(b"d", armored, allowed, namespace="n", signer=""), "^signer must be non-empty text$"),
        ):
            with self.subTest(case=name), self.assertRaisesRegex(ValidationError, pattern):
                call()


class AllowedSignersTests(unittest.TestCase):
    def check(self, third_line: str) -> SignatureVerification:
        armored = signer.armor(signer.envelope(ALICE, b"d"))
        text = "\n".join(["# owners", signer.allowed_line("alice@x", ALICE), third_line])
        return verify_signature(b"d", armored, text, namespace=FUNCTION_NAMESPACE)

    def test_each_unsupported_or_malformed_line_refuses_the_file_by_number(self) -> None:
        key = signer.allowed_line("x", BOB).split(" ", 1)[1]
        wrong_type = base64.b64encode(signer.key_blob(BOB, b"ssh-rsa")).decode()
        short_key = base64.b64encode(signer.string(b"ssh-ed25519") + signer.string(bytes(31))).decode()
        cases = {
            "wildcard principal": (f"*@x {key}", "principal patterns are unsupported"),
            "question-mark principal": (f"b?b@x {key}", "principal patterns are unsupported"),
            "negated principal": (f"!bob@x {key}", "principal patterns are unsupported"),
            "empty principal": (f"a@x,,b@x {key}", "an empty principal"),
            "cert-authority": (f"bob@x cert-authority {key}", "option cert-authority is unsupported"),
            "valid-before": (f'bob@x valid-before="20300101" {key}', "option valid-before is unsupported"),
            "valid-after": (f'bob@x valid-after="20200101" {key}', "option valid-after is unsupported"),
            "unknown option": (f"bob@x frobnicate {key}", "option frobnicate is unsupported"),
            "unquoted namespaces": (f"bob@x namespaces=file {key}", "namespaces must be quoted"),
            "repeated namespaces": (
                f'bob@x namespaces="a",namespaces="b" {key}',
                "namespaces is repeated",
            ),
            "namespace pattern": (f'bob@x namespaces="cement-*" {key}', "namespace patterns are unsupported"),
            "unclosed quote": (f'"bob@x {key}', "a quote is not closed"),
            "no key type": ("bob@x", "no key type"),
            "options then no key type": ('bob@x namespaces="a" AAAA', "no key type"),
            "no key": ("bob@x ssh-ed25519", "no key"),
            "key not base64": ("bob@x ssh-ed25519 not*base64", "the key is not base64"),
            "key blob of another type": (
                f"bob@x ssh-ed25519 {wrong_type}",
                "key type ssh-rsa is unsupported",
            ),
            "31-byte key": (f"bob@x ssh-ed25519 {short_key}", "the key is not a 32-byte Ed25519 key"),
        }
        for name, (line, fragment) in cases.items():
            with self.subTest(case=name), self.assertRaises(ValidationError) as caught:
                self.check(line)
            self.assertIn(fragment, str(caught.exception), name)
            self.assertTrue(str(caught.exception).startswith("allowed signers line 3: "), name)

    def test_lines_cement_never_trusts_are_skipped(self) -> None:
        ecdsa = _fixture("carol.pub").split()[:2]
        for name, line in {
            "ecdsa key": f"carol@x {ecdsa[0]} {ecdsa[1]}",
            "fido key": "dave@x sk-ssh-ed25519@openssh.com AAAAGnNrLXNzaC1lZDI1NTE5QG9wZW5zc2guY29t",
            "certificate key": "erin@x ssh-ed25519-cert-v01@openssh.com AAAA",
            "options before another type": f'carol@x namespaces="a" {ecdsa[0]} {ecdsa[1]}',
            "indented comment": "   # note",
            "blank with spaces": "   ",
        }.items():
            with self.subTest(case=name):
                self.assertEqual(self.check(line).principals, ("alice@x",))

    def test_keywords_are_case_insensitive_and_lines_union_their_principals(self) -> None:
        checked = self.check(signer.allowed_line("ally@x", ALICE, 'NAMESPACES="cement-function-v3"'))
        self.assertEqual(checked.principals, ("alice@x", "ally@x"))
        crlf = "\r\n".join(["# owners", signer.allowed_line("alice@x", ALICE), ""])
        self.assertEqual(
            verify_signature(
                b"d", signer.armor(signer.envelope(ALICE, b"d")), crlf, namespace=FUNCTION_NAMESPACE
            ).principals,
            ("alice@x",),
        )


def _promoted_bundle(directory: pathlib.Path) -> tuple[pathlib.Path, str]:
    """One promoted `{"x": 1}` → `{"y": 1}` function, exported through the CLI."""

    database = str(directory / "ledger.db")
    system = System(database)
    system.register_operation("tenant", "echo", policy=CompilePolicy(2, 1, 0))
    for reviewer in ("alice", "bob"):
        proposal = system.submit_proposal(
            "tenant",
            "echo",
            {"x": 1},
            candidate=Candidate(output={"y": 1}, provenance={}),
            source_id=reviewer,
        )
        system.review("tenant", proposal, reviewer=reviewer, decision="accept")
    system.compile("tenant", "echo")
    system.verify_drafts("tenant", "echo", verified_by="verifier")
    manifest = system.inspect_function_promotion("tenant", "echo")
    system.promote_function(
        "tenant", "echo", expected_function_hash=manifest.function_hash, promoted_by="release"
    )
    system.set_switch("tenant", "echo", mode="follow", actor="person")
    bundle = directory / "bundle.json"
    with contextlib.redirect_stdout(io.StringIO()):
        status = cli.main(
            ["--db", database, "--partition", "tenant", "function", "export", "echo", "--out", str(bundle)]
        )
    assert status == 0
    return bundle, database


class EvalSignatureTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.directory = pathlib.Path(self.temporary.name)
        self.bundle, _ = _promoted_bundle(self.directory)
        self.signature = self.directory / "bundle.json.sig"
        self.signature.write_text(signer.armor(signer.envelope(ALICE, self.bundle.read_bytes())))
        self.allowed = self.directory / "allowed_signers"
        self.allowed.write_text(signer.allowed_line("alice@x", ALICE) + "\n")

    def run_eval(self, *extra: str, value: str = '{"x":1}') -> tuple[int, str, dict]:
        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            status = cli.main(
                ["function", "eval", "--bundle", str(self.bundle), "--input", value, *extra]
            )
        error = json.loads(stderr.getvalue()) if stderr.getvalue() else {}
        return status, stdout.getvalue(), error

    def signed(self, *extra: str, value: str = '{"x":1}') -> tuple[int, str, dict]:
        return self.run_eval(
            "--signature", str(self.signature), "--allowed-signers", str(self.allowed), *extra, value=value
        )

    def test_a_verified_eval_reports_its_signers_and_signing_key(self) -> None:
        status, stdout, _ = self.signed()
        self.assertEqual(status, 0)
        payload = json.loads(stdout)
        self.assertEqual(
            sorted(payload),
            ["artifact_hash", "function_hash", "matched", "output", "signers", "signing_key"],
        )
        self.assertEqual(payload["signers"], ["alice@x"])
        self.assertEqual(payload["signing_key"], _fingerprint(signer.allowed_line("alice@x", ALICE)))
        self.assertEqual(payload["output"], {"y": 1})
        miss, stdout, _ = self.signed(value='{"x":2}')
        self.assertEqual((miss, json.loads(stdout)["matched"]), (6, False))
        self.assertEqual(self.signed("--signer", "alice@x")[0], 0)

    def test_without_the_flags_eval_keeps_its_four_keys(self) -> None:
        status, stdout, _ = self.run_eval()
        self.assertEqual(status, 0)
        self.assertEqual(sorted(json.loads(stdout)), ["artifact_hash", "function_hash", "matched", "output"])

    def test_a_tampered_bundle_refuses_before_it_parses(self) -> None:
        raw = self.bundle.read_bytes()
        self.bundle.write_bytes(raw[:-1] + bytes([raw[-1] ^ 0x01]))
        with mock.patch.object(cli, "parse_function", wraps=cli.parse_function) as parsed:
            status, stdout, error = self.signed()
        self.assertEqual((status, stdout), (5, ""))
        self.assertEqual(error, {"error": "integrity", "message": "signature does not verify"})
        self.assertEqual(parsed.call_count, 0)
        # Control: the same spy sees the parse of an untampered, signed bundle.
        self.bundle.write_bytes(raw)
        with mock.patch.object(cli, "parse_function", wraps=cli.parse_function) as parsed:
            self.assertEqual(self.signed()[0], 0)
        self.assertEqual(parsed.call_count, 1)

    def test_the_flags_pair_or_exit_2(self) -> None:
        for extra, message in (
            (("--signature", "s"), "--signature and --allowed-signers must be given together"),
            (("--allowed-signers", "a"), "--signature and --allowed-signers must be given together"),
            (("--signer", "alice@x"), "--signer needs --signature and --allowed-signers"),
        ):
            with self.subTest(extra=extra):
                status, stdout, error = self.run_eval(*extra)
                self.assertEqual((status, stdout), (2, ""))
                self.assertIn(message, error["message"])

    def test_refusals_keep_stdout_empty_and_use_their_exit_class(self) -> None:
        other = self.directory / "other.sig"
        other.write_text(
            signer.armor(signer.envelope(ALICE, self.bundle.read_bytes(), namespace=b"file"))
        )
        binary = self.directory / "binary.sig"
        binary.write_bytes(b"\xff\xfe")
        cases = (
            (("--signer", "bob@x"), 5, "the signing key is not allowed for that signer"),
            (("--signature", str(other)), 5, "signature namespace is file, expected cement-function-v3"),
            (("--signature", str(self.directory / "missing")), 2, "signature could not be read"),
            (("--signature", str(self.directory)), 2, "signature path must identify a regular file"),
            (("--signature", str(binary)), 2, "signature is not valid UTF-8"),
            (("--allowed-signers", str(self.directory)), 2, "allowed signers file path must identify a regular file"),
        )
        for extra, expected, message in cases:
            arguments = {"--signature": str(self.signature), "--allowed-signers": str(self.allowed)}
            flags = dict(zip(extra[::2], extra[1::2]))
            merged = [item for pair in {**arguments, **flags}.items() for item in pair]
            with self.subTest(extra=extra):
                status, stdout, error = self.run_eval(*merged)
                self.assertEqual((status, stdout), (expected, ""))
                self.assertEqual(error["message"], message)

    def test_both_file_bounds_are_adjacent_pairs(self) -> None:
        armored = self.signature.read_text()
        allowed = self.allowed.read_text()
        for path, base, limit, filler, label in (
            (self.signature, armored, SIGNATURE_MAX_BYTES, "\n", "signature"),
            (self.allowed, allowed, ALLOWED_SIGNERS_MAX_BYTES, "#\n", "allowed signers file"),
        ):
            padding = limit - len(base.encode())
            body = base + (filler * (padding // len(filler) + 1))[:padding]
            self.assertEqual(len(body.encode()), limit)
            with self.subTest(file=label, size=limit):
                path.write_text(body)
                self.assertEqual(self.signed()[0], 0)
            with self.subTest(file=label, size=limit + 1):
                path.write_text(body + "\n")
                status, stdout, error = self.signed()
                self.assertEqual((status, stdout), (2, ""))
                self.assertEqual(error["message"], f"{label} exceeds {limit} bytes")
            path.write_text(base)

    def test_a_wrong_expected_hash_still_refuses_after_a_good_signature(self) -> None:
        status, stdout, error = self.signed("--expected-function-hash", "0" * 64)
        self.assertEqual((status, stdout), (5, ""))
        self.assertEqual(error["message"], "function does not match expected_function_hash")


class EvalProcessFreeTests(unittest.TestCase):
    """G6: a verified eval opens three files, connects no SQLite and starts no process."""

    PROBE = r"""
import json, os, runpy, sys
record, events = sys.argv[1], []
WATCHED = {"open", "sqlite3.connect", "subprocess.Popen", "os.exec", "os.posix_spawn", "os.fork",
           "os.system", "os.spawn"}
def hook(event, args):
    if event in WATCHED:
        first = args[0] if args else None
        path = os.fsdecode(first) if isinstance(first, (str, bytes, os.PathLike)) else repr(first)
        events.append([event, path])
sys.addaudithook(hook)
sys.argv = ["cement_runtime", *sys.argv[2:]]
try:
    if sys.argv[1] == "--control":
        import subprocess
        subprocess.run([sys.executable, "-c", "pass"], check=True)
    else:
        runpy.run_module("cement_runtime", run_name="__main__", alter_sys=True)
finally:
    with open(record, "w", encoding="utf-8") as stream:
        json.dump(events, stream)
"""

    def probe(self, record: pathlib.Path, *arguments: str) -> tuple[int, list[list[str]]]:
        run = subprocess.run(
            [sys.executable, "-c", self.PROBE, str(record), *arguments],
            capture_output=True,
            text=True,
            env={**os.environ, "PYTHONPATH": str(ROOT / "src")},
            check=False,
        )
        return run.returncode, json.loads(record.read_text(encoding="utf-8"))

    def test_a_verified_eval_reads_three_files_and_starts_nothing(self) -> None:
        with tempfile.TemporaryDirectory() as name:
            directory = pathlib.Path(name)
            bundle, _ = _promoted_bundle(directory)
            signature = directory / "bundle.json.sig"
            signature.write_text(signer.armor(signer.envelope(ALICE, bundle.read_bytes())))
            allowed = directory / "allowed_signers"
            allowed.write_text(signer.allowed_line("alice@x", ALICE) + "\n")
            record = directory / "events.json"
            # Control: the hook records process creation.
            status, control = self.probe(record, "--control")
            self.assertEqual(status, 0)
            self.assertIn("subprocess.Popen", [event[0] for event in control])
            status, events = self.probe(
                record,
                "function", "eval", "--bundle", str(bundle), "--input", '{"x":1}',
                "--signature", str(signature), "--allowed-signers", str(allowed),
            )
            self.assertEqual(status, 0)
            self.assertEqual(
                [event for event in events if event[0] != "open"], [],
            )
            opened = {
                event[1]
                for event in events
                if os.path.dirname(os.path.abspath(event[1])) == name and event[1] != str(record)
            }
            self.assertEqual(opened, {str(bundle), str(signature), str(allowed)})


