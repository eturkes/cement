"""Generate the Open WebUI paste-in files: each `cement_*.py` source with `cement_runtime` embedded.

A network-less Open WebUI image cannot install packages, so every pasted file carries the library
as readable source under one digest-named private package. Run from any directory:

    uv run python examples/open_webui/generate.py           # writes examples/open_webui/paste-in/
    uv run python examples/open_webui/generate.py --check   # writes nothing; rc 1 names stale files
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "paste-in"
# Open WebUI runs no command line, so the CLI stays out of the embedded library.
LEFT_OUT = frozenset({"cli", "__main__"})
# Open WebUI rewrites these prefixes anywhere in pasted code (0.12.3 `utils/plugin.py`
# `replace_imports`), so stored bytes would stop matching the generated ones.
REWRITTEN = ("from utils", "from apps", "from main", "from config")
LIBRARY = "cement_runtime"

LOADER = '''
# Generated by {generator} from the Cement repository: do not edit.
# Embedded library: cement_runtime {version}; its sources hash to _CEMENT_DIGEST.
# The embedded source keeps its own line breaks; one of its pragma comments runs past 100
# columns inside the string, where ruff reads no pragma.
# ruff: noqa: E501
_CEMENT_PACKAGE = "_cement_runtime_{short}"
_CEMENT_DIGEST = "{digest}"
_CEMENT_SOURCES = {{
{sources}}}


class _CementImporter:
    """Serves the embedded modules as one package; a digest change gets a new package name."""

    def __init__(self, package: str, sources: dict[str, str]) -> None:
        self.package = package
        self.sources = sources

    def _module(self, fullname: str) -> str | None:
        if fullname == self.package:
            return "__init__"
        prefix = self.package + "."
        name = fullname[len(prefix) :] if fullname.startswith(prefix) else None
        return name if name in self.sources and name != "__init__" else None

    def find_spec(self, fullname: str, _path: object = None, _target: object = None) -> object:
        import importlib.machinery

        name = self._module(fullname)
        if name is None:
            return None
        return importlib.machinery.ModuleSpec(
            fullname, self, origin=f"<cement_runtime>/{{name}}.py", is_package=name == "__init__"
        )

    def create_module(self, _spec: object) -> None:
        return None

    def exec_module(self, module: object) -> None:
        import linecache

        name = self._module(module.__name__)
        filename = f"<cement_runtime>/{{name}}.py"
        source = self.sources[name].removeprefix("\\n")
        linecache.cache[filename] = (len(source), None, source.splitlines(True), filename)
        # The embedded source is the library itself, sealed by `_CEMENT_DIGEST` before any exec.
        exec(compile(source, filename, "exec"), module.__dict__)  # noqa: S102


def _cement_module(name: str) -> object:
    import hashlib
    import importlib
    import sys

    # Checked on every call, not once per process: an edited copy pasted after a clean one would
    # otherwise reuse the clean package and hide the edit.
    seal = hashlib.sha256()
    for module in sorted(_CEMENT_SOURCES):
        text = _CEMENT_SOURCES[module].removeprefix("\\n")
        seal.update(module.encode() + b"\\0" + text.encode() + b"\\0")
    if seal.hexdigest() != _CEMENT_DIGEST:
        raise ImportError("the embedded cement_runtime was edited; {refresh}")
    if not any(getattr(finder, "package", None) == _CEMENT_PACKAGE for finder in sys.meta_path):
        sys.meta_path.insert(0, _CementImporter(_CEMENT_PACKAGE, _CEMENT_SOURCES))
    return importlib.import_module(_CEMENT_PACKAGE + (f".{{name}}" if name else ""))

'''


def _root() -> pathlib.Path:
    # A copy in a worktree relocates `__file__`, so the root is searched, never counted.
    for directory in HERE.parents:
        if (directory / "pyproject.toml").is_file():
            return directory
    raise SystemExit("generate: no pyproject.toml above examples/open_webui")


def _version(root: pathlib.Path) -> str:
    for line in (root / "pyproject.toml").read_text(encoding="utf-8").splitlines():
        if line.startswith("version = "):
            return line.split('"')[1]
    raise SystemExit("generate: pyproject.toml names no version")


def _refuse(label: str, text: str) -> None:
    problems = [token for token in ("'''", *REWRITTEN) if token in text]
    if problems:
        raise SystemExit(f"generate: {label} holds {problems}, which a paste-in cannot carry")


def runtime_sources(root: pathlib.Path) -> dict[str, str]:
    sources = {}
    for path in sorted((root / "src" / LIBRARY).glob("*.py")):
        if path.stem in LEFT_OUT:
            continue
        text = path.read_text(encoding="utf-8")
        _refuse(f"src/{LIBRARY}/{path.name}", text)
        sources[path.stem] = text
    return sources


def digest(sources: dict[str, str]) -> str:
    seal = hashlib.sha256()
    for name in sorted(sources):
        seal.update(name.encode() + b"\0" + sources[name].encode() + b"\0")
    return seal.hexdigest()


def _bindings(node: ast.ImportFrom | ast.Import) -> list[str]:
    if isinstance(node, ast.Import):
        if any(alias.name != LIBRARY and alias.asname is None for alias in node.names) or any(
            not (alias.name == LIBRARY or alias.name.startswith(LIBRARY + "."))
            for alias in node.names
        ):
            # `import cement_runtime.x` binds the root name; a mixed statement binds others.
            raise SystemExit(f"generate: import {LIBRARY} or `import {LIBRARY}.x as y`, alone")
        return [
            f'{alias.asname or alias.name} = _cement_module("{alias.name[len(LIBRARY) + 1 :]}")'
            for alias in node.names
        ]
    submodule = (node.module or "")[len(LIBRARY) + 1 :]
    return [
        f'{alias.asname or alias.name} = _cement_module("{submodule}").{alias.name}'
        for alias in node.names
    ]


def _is_library(node: ast.stmt) -> bool:
    names = (
        [alias.name for alias in node.names]
        if isinstance(node, ast.Import)
        else [node.module or ""]
        if isinstance(node, ast.ImportFrom) and node.level == 0
        else []
    )
    return any(name == LIBRARY or name.startswith(LIBRARY + ".") for name in names)


def render(
    source: str,
    sources: dict[str, str],
    version: str,
    *,
    generator: str = "examples/open_webui/generate.py",
    refresh: str = "paste the generated file again",
) -> str:
    """One paste-in: the source's own imports, the embedded library, bindings, the source body."""

    _refuse("the source", source)
    for name, text in sources.items():
        _refuse(f"embedded {name}", text)
    tree = ast.parse(source)
    imports = [node for node in tree.body if isinstance(node, (ast.Import, ast.ImportFrom))]
    library = [node for node in imports if _is_library(node)]
    if not library:
        raise SystemExit(f"generate: the source imports nothing from {LIBRARY}")
    last = max(node.end_lineno or node.lineno for node in imports)
    first = min(node.lineno for node in library)
    if any(not _is_library(node) and node.lineno > first for node in imports) or any(
        first <= node.lineno <= last and not _is_library(node) for node in tree.body
    ):
        raise SystemExit(f"generate: {LIBRARY} imports must close the import block")
    lines = source.splitlines(keepends=True)
    head = "".join(lines[: first - 1]).rstrip("\n") + "\n"
    body = "".join(lines[last:]).lstrip("\n")
    embedded = "".join(
        f"    \"{name}\": r'''\n{text}''',\n" for name, text in sorted(sources.items())
    )
    key = digest(sources)
    loader = LOADER.format(
        version=version,
        digest=key,
        short=key[:16],
        sources=embedded,
        generator=generator,
        refresh=refresh,
    )
    bindings = "\n".join(binding for node in library for binding in _bindings(node))
    return f"{head}{loader}\n{bindings}\n\n\n{body}"


def targets(root: pathlib.Path) -> dict[pathlib.Path, str]:
    sources = runtime_sources(root)
    version = _version(root)
    return {
        OUT / path.name: render(path.read_text(encoding="utf-8"), sources, version)
        for path in sorted(HERE.glob("cement_*.py"))
    }


def stale(root: pathlib.Path) -> list[str]:
    expected = targets(root)
    present = set(OUT.glob("*.py")) if OUT.is_dir() else set()
    names = [
        path.name
        for path, text in expected.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != text
    ]
    return sorted(names + [path.name for path in present - set(expected)])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the Open WebUI paste-in files.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when stale")
    args = parser.parse_args(argv)
    root = _root()
    if args.check:
        names = stale(root)
        for name in names:
            sys.stderr.write(f"generate: paste-in/{name} is stale; run generate.py\n")
        return 1 if names else 0
    expected = targets(root)
    OUT.mkdir(exist_ok=True)
    for path in set(OUT.glob("*.py")) - set(expected):
        path.unlink()
    for path, text in expected.items():
        path.write_text(text, encoding="utf-8")
        sys.stdout.write(f"wrote {path.relative_to(root)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
